def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def slug(value: str) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9_-]+", "_", value).strip("_")
    if not cleaned:
        raise ValueError("study name becomes empty after sanitization")
    return cleaned[:48]


def bag_identity(path: Path) -> tuple[str, str]:
    match = re.fullmatch(
        r"rosbag2_(\d{4}_\d{2}_\d{2})-(\d{2})_(\d{2})_(\d{2})",
        path.name,
    )
    if match is None:
        raise ValueError(
            f"input bag must be named rosbag2_YYYY_MM_DD-HH_MM_SS: {path}"
        )
    run_date = match.group(1)
    run_time = "_".join(match.groups()[1:])
    return run_date, run_time


def auto_glim(bag: Path) -> Path:
    run_date, run_time = bag_identity(bag)
    name = f"glim_rosbag2_{run_date}-{run_time}"
    candidates = (
        bag.parent / name / "traj_imu.txt",
        bag.parent / name / "tmp" / name / "traj_imu.txt",
    )
    for candidate in candidates:
        if candidate.is_file():
            return candidate.resolve()
    raise FileNotFoundError(
        "matching GLIM traj_imu.txt not found; checked:\n  "
        + "\n  ".join(str(item) for item in candidates)
    )


def load_parameter_document(path: Path) -> tuple[dict, dict]:
    document = yaml.safe_load(path.read_text())
    try:
        parameters = document["/**"]["ros__parameters"]
    except (KeyError, TypeError) as error:
        raise ValueError(
            f"{path} must contain /** -> ros__parameters"
        ) from error
    if not isinstance(parameters, dict):
        raise ValueError(f"{path}: ros__parameters is not a mapping")
    return document, parameters


def canonical(parameters: dict[str, Any]) -> str:
    return json.dumps(parameters, sort_keys=True, separators=(",", ":"))


def write_config(baseline_document: dict, parameters: dict, path: Path) -> None:
    document = json.loads(json.dumps(baseline_document))
    document["/**"]["ros__parameters"] = parameters
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# Generated by localization_replay/optimize_relocation.py.\n"
        + yaml.safe_dump(document, sort_keys=False, default_flow_style=False)
    )


def result_row(result: dict) -> dict:
    datasets = result.get("datasets", [])
    first = datasets[0].get("metrics") if datasets else None
    if first is None:
        return {
            "trial": result["trial"],
            "status": result["status"],
            "aggregate_score": math.inf,
            "position_mean_m": math.nan,
            "position_max_m": math.nan,
            "z_abs_max_m": math.nan,
            "coverage_ratio": 0.0,
            "parameters": canonical(result["parameters"]),
        }
    interval = first["scoring_interval"]
    return {
        "trial": result["trial"],
        "status": result["status"],
        "aggregate_score": result["aggregate_score"],
        "position_mean_m": interval["position_error_m"]["mean"],
        "position_max_m": interval["position_error_m"]["max"],
        "z_abs_max_m": interval["signed_axis_error_m"]["z"]["absolute"]["max"],
        "coverage_ratio": first["data"]["coverage_ratio"],
        "parameters": canonical(result["parameters"]),
    }


class Study:
    def __init__(self, args: argparse.Namespace):
        self.args = args
        self.name = slug(args.study)
        self.directory = args.study_root.resolve() / self.name
        self.config_dir = self.directory / "configs"
        self.metrics_dir = self.directory / "metrics"
        self.log_dir = self.directory / "logs"
        self.results_path = self.directory / "results.jsonl"
        self.manifest_path = self.directory / "study.json"
        self.snapshot_dir = self.directory / "snapshot"
        self.snapshot_launch = self.snapshot_dir / "slam_bag_rviz_launch.py"
        self.snapshot_super_lio = self.snapshot_dir / "install/super_lio"
        self.snapshot_basic = self.snapshot_dir / "install/basic"
        self.results: list[dict] = []
        self.by_signature: dict[str, dict] = {}

        self.bags = [path.resolve() for path in args.bag]
        self.glims = [auto_glim(path) for path in self.bags]
        baseline_load_path = args.baseline_config
        search_space_load_path = args.search_space
        if args.resume and (self.snapshot_dir / "baseline_config.yaml").is_file():
            baseline_load_path = self.snapshot_dir / "baseline_config.yaml"
        if args.resume and (self.snapshot_dir / "search_space.yaml").is_file():
            search_space_load_path = self.snapshot_dir / "search_space.yaml"
        self.baseline_document, baseline_parameters = load_parameter_document(
            baseline_load_path
        )
        self.baseline_parameters = dict(baseline_parameters)
        space = yaml.safe_load(search_space_load_path.read_text())
        try:
            self.parameter_names = list(space["profiles"][args.profile])
            all_specs = space["parameters"]
        except (KeyError, TypeError) as error:
            raise ValueError(
                f"profile {args.profile!r} is absent or invalid in {args.search_space}"
            ) from error
        self.search_values = {
            name: list(all_specs[name]["values"]) for name in self.parameter_names
        }
        missing = [name for name in self.parameter_names if name not in baseline_parameters]
        if missing:
            raise ValueError(f"baseline config is missing parameters: {missing}")

    def prepare(self) -> None:
        if self.directory.exists() and not self.args.resume:
            raise FileExistsError(
                f"study already exists: {self.directory}; use --resume or a new --study"
            )
        self.config_dir.mkdir(parents=True, exist_ok=True)
        self.metrics_dir.mkdir(parents=True, exist_ok=True)
        self.log_dir.mkdir(parents=True, exist_ok=True)
        self._prepare_snapshot()
        if self.results_path.is_file():
            for line in self.results_path.read_text().splitlines():
                if not line.strip():
                    continue
                result = json.loads(line)
                self.results.append(result)
                self.by_signature[result["signature"]] = result

        manifest = {
            "study": self.name,
            "created_or_resumed_at": datetime.now().astimezone().isoformat(),
            "input_bags": [str(path) for path in self.bags],
            "glim_trajectories": [str(path) for path in self.glims],
            "baseline_config": str(self.args.baseline_config.resolve()),
            "baseline_config_sha256": sha256(
                self.snapshot_dir / "baseline_config.yaml"
            ),
            "snapshot_baseline_config": str(
                (self.snapshot_dir / "baseline_config.yaml").resolve()
            ),
            "snapshot_launch": str(self.snapshot_launch.resolve()),
            "snapshot_launch_sha256": sha256(self.snapshot_launch),
            "snapshot_relocation_node_sha256": sha256(
                self.snapshot_super_lio / "lib/super_lio/relocation_node"
            ),
            "snapshot_liblio_sha256": sha256(
                self.snapshot_super_lio / "lib/liblio.so"
            ),
            "search_space": str(self.args.search_space.resolve()),
            "search_space_sha256": sha256(
                self.snapshot_dir / "search_space.yaml"
            ),
            "profile": self.args.profile,
            "parameter_order": self.parameter_names,
            "play_rate": self.args.rate,
            "score_trim_sec": self.args.score_trim_sec,
            "spatial_alignment": (
                "candidate-independent fixed transform from each original source "
                "bag /lio/odom and its matching GLIM traj_imu.txt"
            ),
            "time_alignment": "raw header/sensor timestamps; no fitted offset",
            "output_bag_root": str(self.args.output_root.resolve()),
        }
        if self.manifest_path.is_file() and self.args.resume:
            previous = json.loads(self.manifest_path.read_text())
            compatibility_keys = (
                "input_bags",
                "glim_trajectories",
                "baseline_config",
                "baseline_config_sha256",
                "search_space",
                "search_space_sha256",
                "profile",
                "parameter_order",
                "play_rate",
                "score_trim_sec",
                "output_bag_root",
            )
            changed = [
                key for key in compatibility_keys
                if previous.get(key) != manifest.get(key)
            ]
            if changed:
                raise ValueError(
                    "refusing to mix incompatible trials in resumed study; "
                    f"changed fields: {changed}"
                )
            manifest["original_created_at"] = previous.get(
                "original_created_at", previous.get("created_or_resumed_at")
            )
        self.manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")

    def _prepare_snapshot(self) -> None:
        """Freeze every user-editable launch/config/binary input for the study."""
        if self.snapshot_dir.exists():
            required = (
                self.snapshot_launch,
                self.snapshot_dir / "baseline_config.yaml",
                self.snapshot_dir / "search_space.yaml",
                self.snapshot_super_lio / "lib/super_lio/relocation_node",
                self.snapshot_super_lio / "lib/liblio.so",
                self.snapshot_basic / "lib/libbasic.so",
            )
            missing = [str(path) for path in required if not path.is_file()]
            if missing:
                raise RuntimeError(f"incomplete study snapshot: {missing}")
            return

        bidex_prefix = Path(
            subprocess.check_output(
                ("ros2", "pkg", "prefix", "bidex_ros"), text=True
            ).strip()
        )
        super_lio_prefix = Path(
            subprocess.check_output(
                ("ros2", "pkg", "prefix", "super_lio"), text=True
            ).strip()
        )
        basic_prefix = Path(
            subprocess.check_output(
                ("ros2", "pkg", "prefix", "basic"), text=True
            ).strip()
        )
        launch_source = (
            bidex_prefix / "share/bidex_ros/launch/slam_bag_rviz_launch.py"
        )
        self.snapshot_dir.mkdir(parents=True)
        shutil.copy2(launch_source, self.snapshot_launch)
        shutil.copy2(
            self.args.baseline_config, self.snapshot_dir / "baseline_config.yaml"
        )
        shutil.copy2(
            self.args.search_space, self.snapshot_dir / "search_space.yaml"
        )
        shutil.copytree(super_lio_prefix, self.snapshot_super_lio)
        shutil.copytree(basic_prefix, self.snapshot_basic)

    def output_bag(self, source: Path, trial: int) -> Path:
        suffix = source.name.removeprefix("rosbag2_")
        return (
            self.args.output_root.resolve()
            / f"superlio_{suffix}_opt_{self.name}_t{trial:03d}"
        )

    def run_candidate(self, parameters: dict, reason: str) -> dict:
        signature = hashlib.sha256(canonical(parameters).encode()).hexdigest()
        if signature in self.by_signature:
            prior = self.by_signature[signature]
            print(
                f"reuse t{prior['trial']:03d} score={prior['aggregate_score']:.6f} "
                f"({reason})",
                flush=True,
            )
            return prior
        if self.args.max_trials is not None and len(self.results) >= self.args.max_trials:
            raise StopIteration

        trial = len(self.results)
        config_path = self.config_dir / f"trial_{trial:03d}.yaml"
        write_config(self.baseline_document, parameters, config_path)
        result = {
            "trial": trial,
            "signature": signature,
            "status": "planned" if not self.args.execute else "running",
            "reason": reason,
            "parameters": parameters,
            "config": str(config_path),
            "datasets": [],
            "aggregate_score": math.inf,
        }
        print(f"\n[t{trial:03d}] {reason}", flush=True)

        if not self.args.execute:
            for bag, glim in zip(self.bags, self.glims):
                output_bag = self.output_bag(bag, trial)
                command = self.record_command(
                    bag, output_bag, config_path, trial, dry_run=True
                )
                print(" ".join(map(str, command)), flush=True)
                print(f"  GLIM: {glim}", flush=True)
                result["datasets"].append(
                    {"source_bag": str(bag), "output_bag": str(output_bag)}
                )
            result["status"] = "planned"
            self.save_result(result)
            return result

        scores = []
        try:
            for dataset_index, (bag, glim) in enumerate(zip(self.bags, self.glims)):
                output_bag = self.output_bag(bag, trial)
                dataset_log_dir = self.log_dir / f"trial_{trial:03d}_d{dataset_index}"
                command = self.record_command(
                    bag, output_bag, config_path, trial, log_dir=dataset_log_dir
                )
                subprocess.run(command, check=True)

                metrics_path = (
                    self.metrics_dir / f"trial_{trial:03d}_d{dataset_index}.json"
                )
                evaluate_command = [
                    sys.executable,
                    str(SCRIPT_DIR / "evaluate_relocation_trial.py"),
                    "--estimated-bag",
                    str(output_bag),
                    "--anchor-bag",
                    str(bag),
                    "--glim-trajectory",
                    str(glim),
                    "--output",
                    str(metrics_path),
                    "--score-trim-sec",
                    str(self.args.score_trim_sec),
                    "--minimum-coverage",
                    str(self.args.minimum_coverage),
                ]
                subprocess.run(evaluate_command, check=True)
                metrics = json.loads(metrics_path.read_text())
                score_value = float(metrics["objective"]["value"])
                scores.append(score_value)
                result["datasets"].append(
                    {
                        "source_bag": str(bag),
                        "glim_trajectory": str(glim),
                        "output_bag": str(output_bag),
                        "metrics_path": str(metrics_path),
                        "metrics": metrics,
                    }
                )
            result["aggregate_score"] = 0.75 * (sum(scores) / len(scores)) + 0.25 * max(scores)
            result["status"] = "complete"
        except (subprocess.CalledProcessError, Exception) as error:
            result["status"] = "failed"
            result["error"] = f"{type(error).__name__}: {error}"
            result["aggregate_score"] = math.inf
            print(f"trial failed: {result['error']}", file=sys.stderr, flush=True)
            if self.args.fail_fast:
                self.save_result(result)
                raise
        self.save_result(result)
        print(
            f"[t{trial:03d}] status={result['status']} "
            f"score={result['aggregate_score']:.6f}",
            flush=True,
        )
        return result

    def record_command(
        self,
        bag: Path,
        output_bag: Path,
        config_path: Path,
        trial: int,
        log_dir: Path | None = None,
        dry_run: bool = False,
    ) -> list[str]:
        command = [
            str(SCRIPT_DIR / "record_relocation_trial.sh"),
            "--bag",
            str(bag),
            "--output",
            str(output_bag),
            "--config",
            str(config_path),
            "--rate",
            str(self.args.rate),
            "--start-offset",
            str(self.args.start_offset),
            "--domain-id",
            str(self.args.domain_id),
            "--launch-file",
            str(self.snapshot_launch),
            "--super-lio-prefix",
            str(self.snapshot_super_lio),
            "--basic-prefix",
            str(self.snapshot_basic),
        ]
        if log_dir is not None:
            command.extend(("--log-dir", str(log_dir)))
        if dry_run:
            command.append("--dry-run")
        return command

    def save_result(self, result: dict) -> None:
        with self.results_path.open("a") as stream:
            stream.write(json.dumps(result, sort_keys=True) + "\n")
        self.results.append(result)
        self.by_signature[result["signature"]] = result
        self.write_leaderboard()

    def write_leaderboard(self) -> None:
        rows = [result_row(item) for item in self.results]
        rows.sort(key=lambda item: item["aggregate_score"])
        path = self.directory / "leaderboard.csv"
        with path.open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)

    def finalize(self, install_global: bool) -> dict | None:
        complete = [item for item in self.results if item["status"] == "complete"]
        if not complete:
            return None
        best = min(complete, key=lambda item: item["aggregate_score"])
        best_study_config = self.directory / "relocation_optimized.yaml"
        shutil.copy2(best["config"], best_study_config)
        if install_global and self.args.optimized_config is not None:
            self.args.optimized_config.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(best["config"], self.args.optimized_config)
        summary = {
            "best_trial": best["trial"],
            "best_score": best["aggregate_score"],
            "best_parameters": best["parameters"],
            "study_config": str(best_study_config),
            "installed_optimized_config": (
                str(self.args.optimized_config)
                if install_global and self.args.optimized_config is not None
                else None
            ),
        }
        (self.directory / "best.json").write_text(
            json.dumps(summary, indent=2, sort_keys=True) + "\n"
        )
        return summary


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--bag",
        action="append",
        type=Path,
        required=True,
        help="source rosbag; repeat for cross-dataset optimization",
    )
    parser.add_argument("--baseline-config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--search-space", type=Path, default=DEFAULT_SPACE)
    parser.add_argument("--profile", choices=("imu", "core", "full"), default="imu")
    parser.add_argument(
        "--study",
        default=datetime.now().strftime("reloc_%Y%m%d_%H%M%S"),
    )
    parser.add_argument("--study-root", type=Path, default=DEFAULT_STUDY_ROOT)
    parser.add_argument("--output-root", type=Path, default=DEFAULT_BAG_ROOT)
    parser.add_argument(
        "--optimized-config", type=Path, default=DEFAULT_OPTIMIZED_CONFIG
    )
    parser.add_argument("--rate", type=float, default=1.0)
    parser.add_argument("--start-offset", type=float, default=0.0)
    parser.add_argument("--domain-id", type=int, default=142)
    parser.add_argument("--score-trim-sec", type=float, default=0.0)
    parser.add_argument("--minimum-coverage", type=float, default=0.90)
    parser.add_argument("--rounds", type=int, default=1)
    parser.add_argument("--max-trials", type=int, default=None)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument(
        "--snapshot-only",
        action="store_true",
        help="freeze config/launch/binaries and write study metadata, then exit",
    )
    parser.add_argument("--fail-fast", action="store_true")
    parser.add_argument(
        "--install-partial-best",
        action="store_true",
        help=(
            "also update --optimized-config when --max-trials stops the search "
            "early; otherwise only the study-local winner is written"
        ),
    )
    parser.add_argument(
        "--execute",
        action="store_true",
        help="actually run ROS; without this flag only a plan is generated",
    )
    args = parser.parse_args()
    if not math.isfinite(args.rate) or args.rate <= 0.0:
        parser.error("--rate must be positive")
    if args.rounds <= 0:
        parser.error("--rounds must be positive")
    if args.max_trials is not None and args.max_trials <= 0:
        parser.error("--max-trials must be positive")
    if not 0 <= args.domain_id <= 232:
        parser.error("--domain-id must be in [0, 232]")
    args.baseline_config = args.baseline_config.resolve()
    args.search_space = args.search_space.resolve()
    for path in args.bag:
        if not (path / "metadata.yaml").is_file():
            parser.error(f"invalid rosbag directory: {path}")
    output_root = args.output_root.resolve()
    stopped_early = False
    try:
        output_root.relative_to(DEFAULT_BAG_ROOT)
    except ValueError:
        parser.error("--output-root must be /workspace/rosbag or a descendant")
    return args


def main() -> None:
    args = parse_args()
    study = Study(args)
    study.prepare()
    print(f"study: {study.directory}")
    print(f"mode: {'EXECUTE' if args.execute else 'PLAN ONLY'}")
    print(f"profile: {args.profile} ({len(study.parameter_names)} parameters)")
    print("objective: same timestamps + one frozen source-bag spatial anchor")
    if args.snapshot_only:
        print(f"snapshot ready: {study.snapshot_dir}")
        return

    current = dict(study.baseline_parameters)
    try:
        baseline = study.run_candidate(current, "baseline")
        if baseline["status"] == "complete":
            current = dict(baseline["parameters"])

        for round_index in range(args.rounds):
            for parameter in study.parameter_names:
                candidates = []
                for value in study.search_values[parameter]:
                    if value == current[parameter]:
                        continue
                    candidate = dict(current)
                    candidate[parameter] = value
                    result = study.run_candidate(
                        candidate,
                        f"round {round_index + 1}: {parameter}={value}",
                    )
                    if result["status"] == "complete":
                        candidates.append(result)
                incumbent_signature = hashlib.sha256(
                    canonical(current).encode()
                ).hexdigest()
                incumbent = study.by_signature.get(incumbent_signature)
                if incumbent is not None and incumbent["status"] == "complete":
                    candidates.append(incumbent)
                if candidates:
                    best = min(candidates, key=lambda item: item["aggregate_score"])
                    current = dict(best["parameters"])
                    print(
                        f"accepted after {parameter}: t{best['trial']:03d}, "
                        f"score={best['aggregate_score']:.6f}",
                        flush=True,
                    )
    except StopIteration:
        stopped_early = True
        print(f"stopped at --max-trials={args.max_trials}", flush=True)

    best = study.finalize(
        install_global=(not stopped_early or args.install_partial_best)
    )
    if not args.execute:
        planned = len([item for item in study.results if item["status"] == "planned"])
        print(f"planned trials: {planned}")
        print("rerun with --execute using a fresh --study name to process them")
    elif best is None:
        raise SystemExit("no trial completed successfully")
    else:
        print(json.dumps(best, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
