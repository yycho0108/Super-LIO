import yaml


SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
DEFAULT_CONFIG = (
    REPO_ROOT / "src/super_lio/config/relocation_real_20260802.yaml"
)
DEFAULT_SPACE = SCRIPT_DIR / "relocation_search_space.yaml"
DEFAULT_BAG_ROOT = Path("/workspace/rosbag")
